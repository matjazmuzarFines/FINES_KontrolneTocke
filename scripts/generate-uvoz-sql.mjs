// Generates supabase/005_uvoz_postopkov.sql from src/uvoz-postopki.json (procedures of the "Končni preizkus" form).
// Run: node scripts/generate-uvoz-sql.mjs
// The whole import is ONE DO block with the data as JSON: Supabase SQL Editor may run separate statements in
// different sessions, so a temporary table from an earlier statement is not visible later.
import { readFileSync, writeFileSync } from 'node:fs';

const rows = JSON.parse(readFileSync(new URL('../src/uvoz-postopki.json', import.meta.url), 'utf8'));
const data = rows.map(r => ({
  code: r.code, name: r.name, instruction: r.instruction, input_type: r.input_type, default_unit: r.default_unit, grp: r.group,
  phase: r.phase, status: r.status, default_order: r.default_order, sequence_number: r.no, internal_note: r.internal_note, affiliations: r.affiliations,
}));
const json = JSON.stringify(data, null, 0).replaceAll('},{', '},\n{');
if (json.includes('$json$')) throw new Error('Data contains the dollar-quote tag.');
// Same row source for every statement below.
const u = `jsonb_to_recordset(v_rows) AS u(code text, name text, instruction text, input_type text, default_unit text, grp text, phase text, status text, default_order integer, sequence_number integer, internal_note text, affiliations jsonb)`;

const sql = `-- FINES Kontrolne točke: uvoz ${rows.length} kontrolnih postopkov iz obrazca »Končni preizkus« (data/2209120930AN_Digitalni obrazec_Končni_Preizkus 1.xlsm).
-- GENERATED by scripts/generate-uvoz-sql.mjs from src/uvoz-postopki.json – do not edit by hand.
-- Execute after 004_pripadnosti_meritve.sql. Can be repeated: existing codes are updated, missing ones added, nothing is deleted.
-- KP-0001 … KP-0010 keep their ID and links; affiliations of imported procedures are set to the ones from the form.
-- One DO block = one atomic statement: on any error nothing is changed.
DO $uvoz$
DECLARE
  v_rows jsonb := $json$${json}$json$::jsonb;
  v_count integer;
BEGIN
  IF to_regclass('public.ln_kp_postopki_pripadnost') IS NULL THEN
    RAISE EXCEPTION 'Najprej izvedite 003_sifranti.sql in 004_pripadnosti_meritve.sql.';
  END IF;
  SELECT count(*) INTO v_count FROM ${u}
    WHERE NOT EXISTS (SELECT 1 FROM public.kp_tipi_vnosa WHERE code = u.input_type)
       OR NOT EXISTS (SELECT 1 FROM public.kp_skupine WHERE code = u.grp)
       OR NOT EXISTS (SELECT 1 FROM public.kp_faze_testa WHERE code = u.phase)
       OR NOT EXISTS (SELECT 1 FROM public.kp_statusi_postopkov WHERE code = u.status)
       OR EXISTS (SELECT 1 FROM jsonb_array_elements_text(u.affiliations) c WHERE NOT EXISTS (SELECT 1 FROM public.kp_pripadnosti WHERE code = c));
  IF v_count > 0 THEN RAISE EXCEPTION 'Uvoz uporablja vrednost, ki je ni v šifrantih (% postopkov).', v_count; END IF;

  UPDATE public.kp_postopki p SET
    name = u.name, instruction = u.instruction, default_unit = u.default_unit, default_order = u.default_order, sequence_number = u.sequence_number,
    internal_note = u.internal_note, active = true, visible = true,
    input_type_id = (SELECT id FROM public.kp_tipi_vnosa WHERE code = u.input_type),
    group_id = (SELECT id FROM public.kp_skupine WHERE code = u.grp),
    test_phase_id = (SELECT id FROM public.kp_faze_testa WHERE code = u.phase),
    status_id = (SELECT id FROM public.kp_statusi_postopkov WHERE code = u.status)
  FROM ${u} WHERE p.code = u.code;

  INSERT INTO public.kp_postopki(code, name, instruction, default_unit, default_order, sequence_number, internal_note, input_type_id, group_id, test_phase_id, status_id)
  SELECT u.code, u.name, u.instruction, u.default_unit, u.default_order, u.sequence_number, u.internal_note,
    (SELECT id FROM public.kp_tipi_vnosa WHERE code = u.input_type), (SELECT id FROM public.kp_skupine WHERE code = u.grp),
    (SELECT id FROM public.kp_faze_testa WHERE code = u.phase), (SELECT id FROM public.kp_statusi_postopkov WHERE code = u.status)
  FROM ${u} WHERE NOT EXISTS (SELECT 1 FROM public.kp_postopki p WHERE p.code = u.code);

  -- Affiliations: hide the ones that are not in the form, add or restore the others.
  UPDATE public.ln_kp_postopki_pripadnost l SET visible = EXISTS (
    SELECT 1 FROM ${u} JOIN public.kp_pripadnosti a ON a.code IN (SELECT jsonb_array_elements_text(u.affiliations))
    WHERE u.code = p.code AND a.id = l.id_pripadnosti)
  FROM public.kp_postopki p WHERE p.id = l.id_postopka AND p.code IN (SELECT u.code FROM ${u});
  INSERT INTO public.ln_kp_postopki_pripadnost(id_postopka, id_pripadnosti)
  SELECT p.id, a.id FROM ${u} JOIN public.kp_postopki p ON p.code = u.code
    JOIN public.kp_pripadnosti a ON a.code IN (SELECT jsonb_array_elements_text(u.affiliations))
  ON CONFLICT (id_postopka, id_pripadnosti) DO UPDATE SET visible = true;

  RAISE NOTICE 'Uvoženih postopkov: %', jsonb_array_length(v_rows);
END;
$uvoz$;
`;
writeFileSync(new URL('../supabase/005_uvoz_postopkov.sql', import.meta.url), sql);
console.log(`supabase/005_uvoz_postopkov.sql: ${rows.length} postopkov`);
