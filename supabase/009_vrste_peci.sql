-- FINES Kontrolne točke 5.02: oven type (tip) and kind (vrsta) are recognised from the oven name.
-- Execute ONCE in Supabase SQL Editor after 008_tipi_peci.sql. One DO block = one atomic statement; nothing is deleted.
--   kp_tipi_peci.patterns   – name beginnings of a type, e.g. OC-B = FB, HTB (the longest match wins: FBM is OC-A, HTBP is PV-B).
--   kp_vrste_peci           – kinds: S Smart, D2 Digital, M2 Manual, CL, HTB; patterns are words in the name (S, SMART / D2 / M2, M / CL).
--                             oven_type_id + name_prefix limit a kind to one type: CL is only for OC-B ovens whose name starts with FB,
--                             HTB (no patterns) is every OC-B oven whose name starts with HTB.
--                             A limited kind wins over a general one (FB5-S CL is CL, not S; HTB10-D2 is HTB).
--   kp_artikli.oven_type_id / oven_variant_id – manual choice; NULL means "recognised from the name".
--   ln_kp_tip_postopki.oven_variant_id – NULL = the procedure is for all kinds of the type.
-- The 11 combined types of 008 (OC-B S, OC-B CL …) are hidden; their ovens and test procedures move to the new type + kind.
DO $migracija$
DECLARE t text;
BEGIN
  IF to_regclass('public.kp_tipi_peci') IS NULL THEN RAISE EXCEPTION 'Najprej izvedite 008_tipi_peci.sql.'; END IF;
  IF to_regclass('public.kp_vrste_peci') IS NOT NULL THEN RAISE EXCEPTION 'Migracija 009 je že izvedena.'; END IF;

  CREATE TABLE public.kp_vrste_peci (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (length(btrim(code)) > 0),
    name text NOT NULL CHECK (length(btrim(name)) > 0),
    patterns text NOT NULL DEFAULT '',
    oven_type_id bigint REFERENCES public.kp_tipi_peci(id),
    name_prefix text NOT NULL DEFAULT '',
    sort_order integer NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
  );
  EXECUTE 'ALTER TABLE public.kp_vrste_peci ENABLE ROW LEVEL SECURITY';
  EXECUTE 'REVOKE ALL ON public.kp_vrste_peci FROM anon, authenticated';
  EXECUTE 'GRANT SELECT, INSERT, UPDATE ON public.kp_vrste_peci TO authenticated';
  EXECUTE 'CREATE TRIGGER touch_updated_at BEFORE UPDATE ON public.kp_vrste_peci FOR EACH ROW EXECUTE FUNCTION public.kp_touch_updated_at()';
  EXECUTE 'CREATE TRIGGER prevent_delete BEFORE DELETE ON public.kp_vrste_peci FOR EACH ROW EXECUTE FUNCTION public.kp_prevent_delete()';
  EXECUTE 'CREATE POLICY read_members ON public.kp_vrste_peci FOR SELECT TO authenticated USING (public.kp_role() IS NOT NULL)';
  EXECUTE 'CREATE POLICY insert_developers ON public.kp_vrste_peci FOR INSERT TO authenticated WITH CHECK (public.kp_role() IN (''developer'',''admin''))';
  EXECUTE 'CREATE POLICY update_developers ON public.kp_vrste_peci FOR UPDATE TO authenticated USING (public.kp_role() IN (''developer'',''admin'')) WITH CHECK (public.kp_role() IN (''developer'',''admin''))';
  -- IDs match src/lookups.ts (demo mode).
  INSERT INTO public.kp_vrste_peci(id, code, name, patterns, sort_order) VALUES (1,'S','Smart','S,SMART',10), (2,'D2','Digital','D2',20), (3,'M2','Manual','M2,M',30);

  ALTER TABLE public.kp_tipi_peci ADD COLUMN patterns text NOT NULL DEFAULT '';
  ALTER TABLE public.kp_artikli ADD COLUMN oven_variant_id bigint REFERENCES public.kp_vrste_peci(id);
  ALTER TABLE public.ln_kp_tip_postopki ADD COLUMN oven_variant_id bigint REFERENCES public.kp_vrste_peci(id);
  ALTER TABLE public.ln_kp_tip_postopki DROP CONSTRAINT ln_kp_tip_postopki_oven_type_id_procedure_id_key;
  ALTER TABLE public.ln_kp_tip_postopki ADD CONSTRAINT ln_kp_tip_postopki_unique UNIQUE NULLS NOT DISTINCT (oven_type_id, oven_variant_id, procedure_id);

  -- SCH of 008 stays SCH; the other types continue the numbering after the 11 types of 008 (IDs 12 … 16, the same as the demo mode).
  UPDATE public.kp_tipi_peci SET patterns = 'SCH', sort_order = 160 WHERE code = 'SCH';
  PERFORM setval(pg_get_serial_sequence('public.kp_tipi_peci', 'id'), greatest(11, (SELECT max(id) FROM public.kp_tipi_peci)));
  INSERT INTO public.kp_tipi_peci(code, name, affiliation_id, patterns, sort_order)
  SELECT v.code, v.code, (SELECT a.id FROM public.kp_pripadnosti a WHERE a.code = v.affiliation), v.patterns, v.sort_order
  FROM (VALUES ('OC-B','OCB','FB,HTB',110), ('OC-A','OCA','FBM',120), ('OD-C','ODC','FD',130), ('PV-B','PV-B','HTBP',140), ('OP-D','OPD','ES660',150))
    AS v(code, affiliation, patterns, sort_order)
  ORDER BY v.sort_order;
  INSERT INTO public.kp_vrste_peci(id, code, name, patterns, oven_type_id, name_prefix, sort_order)
  SELECT v.id, v.code, v.code, v.patterns, t.id, v.prefix, v.sort_order FROM public.kp_tipi_peci t
  CROSS JOIN (VALUES (4,'CL','CL','FB',40), (5,'HTB','','HTB',50)) AS v(id, code, patterns, prefix, sort_order) WHERE t.code = 'OC-B';
  PERFORM setval(pg_get_serial_sequence('public.kp_vrste_peci', 'id'), 5);

  CREATE TEMP TABLE kp_tip_map(old_code text, type_code text, variant_code text) ON COMMIT DROP;
  INSERT INTO kp_tip_map VALUES ('OC-B S','OC-B','S'), ('OC-B CL','OC-B','CL'), ('OC-A S','OC-A','S'), ('OC-A S CL','OC-A','S'), ('OD-C S','OD-C','S'), ('OD-C D2','OD-C','D2'),
    ('OP-D M','OP-D','M2'), ('OP-D D2','OP-D','D2'), ('PV-B S','PV-B','S'), ('PV-B D2','PV-B','D2'), ('SCH','SCH',NULL);
  UPDATE public.kp_artikli a SET oven_type_id = n.id, oven_variant_id = v.id
  FROM kp_tip_map m JOIN public.kp_tipi_peci o ON o.code = m.old_code JOIN public.kp_tipi_peci n ON n.code = m.type_code LEFT JOIN public.kp_vrste_peci v ON v.code = m.variant_code
  WHERE a.oven_type_id = o.id AND o.code <> n.code;
  INSERT INTO public.ln_kp_tip_postopki(oven_type_id, oven_variant_id, procedure_id, sort_order)
  SELECT n.id, v.id, r.procedure_id, min(r.sort_order)
  FROM public.ln_kp_tip_postopki r JOIN public.kp_tipi_peci o ON o.id = r.oven_type_id JOIN kp_tip_map m ON m.old_code = o.code
    JOIN public.kp_tipi_peci n ON n.code = m.type_code LEFT JOIN public.kp_vrste_peci v ON v.code = m.variant_code
  WHERE r.visible AND o.code <> n.code
  GROUP BY n.id, v.id, r.procedure_id
  ON CONFLICT DO NOTHING;
  UPDATE public.ln_kp_tip_postopki SET visible = false WHERE oven_type_id IN (SELECT o.id FROM public.kp_tipi_peci o JOIN kp_tip_map m ON m.old_code = o.code AND o.code <> m.type_code);
  UPDATE public.kp_tipi_peci SET visible = false WHERE code IN (SELECT old_code FROM kp_tip_map WHERE old_code <> type_code);
END;
$migracija$;
