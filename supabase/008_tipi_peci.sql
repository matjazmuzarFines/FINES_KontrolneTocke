-- FINES Kontrolne točke 5.01: oven types (pripadnost peči) with their own test procedure.
-- Execute ONCE in Supabase SQL Editor after 007_status_artikla.sql. One DO block = one atomic statement.
--   kp_tipi_peci            – oven types, e.g. OC-B S, OC-B CL; affiliation_id is the procedure affiliation (OCB …) used to suggest procedures.
--   kp_artikli.oven_type_id – the type of an oven (šifra); empty until it is set in the app or by the sync.
--   ln_kp_tip_postopki      – test procedure of a type: procedures every oven of the type gets.
-- Removing a procedure from a type sets visible = false; nothing is deleted.
DO $migracija$
DECLARE t text;
BEGIN
  IF to_regclass('public.kp_tipi_peci') IS NOT NULL THEN RAISE EXCEPTION 'Migracija 008 je že izvedena.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'kp_artikli' AND column_name = 'ready_for_production') THEN
    RAISE EXCEPTION 'Najprej izvedite 007_status_artikla.sql.';
  END IF;

  CREATE TABLE public.kp_tipi_peci (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (length(btrim(code)) > 0),
    name text NOT NULL CHECK (length(btrim(name)) > 0),
    affiliation_id bigint REFERENCES public.kp_pripadnosti(id),
    sort_order integer NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
  );
  ALTER TABLE public.kp_artikli ADD COLUMN oven_type_id bigint REFERENCES public.kp_tipi_peci(id);
  CREATE INDEX ON public.kp_artikli(oven_type_id);
  CREATE TABLE public.ln_kp_tip_postopki (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oven_type_id bigint NOT NULL REFERENCES public.kp_tipi_peci(id),
    procedure_id bigint NOT NULL REFERENCES public.kp_postopki(id),
    sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    visible boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (oven_type_id, procedure_id)
  );
  CREATE INDEX ON public.ln_kp_tip_postopki(procedure_id);

  FOREACH t IN ARRAY ARRAY['kp_tipi_peci','ln_kp_tip_postopki'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE ON public.%I TO authenticated', t);
    EXECUTE format('CREATE TRIGGER touch_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.kp_touch_updated_at()', t);
    EXECUTE format('CREATE TRIGGER prevent_delete BEFORE DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.kp_prevent_delete()', t);
    EXECUTE format('CREATE POLICY read_members ON public.%I FOR SELECT TO authenticated USING (public.kp_role() IS NOT NULL)', t);
    EXECUTE format('CREATE POLICY insert_developers ON public.%I FOR INSERT TO authenticated WITH CHECK (public.kp_role() IN (''developer'',''admin''))', t);
    EXECUTE format('CREATE POLICY update_developers ON public.%I FOR UPDATE TO authenticated USING (public.kp_role() IN (''developer'',''admin'')) WITH CHECK (public.kp_role() IN (''developer'',''admin''))', t);
  END LOOP;

  -- IDs 1 … 11 match src/lookups.ts (demo mode).
  INSERT INTO public.kp_tipi_peci(id, code, name, affiliation_id, sort_order)
  SELECT v.id, v.code, v.code, (SELECT a.id FROM public.kp_pripadnosti a WHERE a.code = v.affiliation), v.id * 10
  FROM (VALUES (1,'OC-B S','OCB'), (2,'OC-B CL','OCB'), (3,'OC-A S','OCA'), (4,'OC-A S CL','OCA'), (5,'OD-C S','ODC'), (6,'OD-C D2','ODC'),
               (7,'OP-D M','OPD'), (8,'OP-D D2','OPD'), (9,'PV-B S','PV-B'), (10,'PV-B D2','PV-B'), (11,'SCH','SCH')) AS v(id, code, affiliation);
  PERFORM setval(pg_get_serial_sequence('public.kp_tipi_peci', 'id'), 11);
END;
$migracija$;
